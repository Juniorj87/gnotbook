import 'dotenv/config';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PACK = path.join(ROOT, 'nft-collection');
const JWT = process.env.PINATA_JWT;
if (!JWT) {
  console.error('PINATA_JWT is missing. Copy .env.example to .env and add a Pinata JWT with pinFileToIPFS permission.');
  process.exit(1);
}

async function filesIn(dir) {
  const out=[];
  async function walk(current) {
    for (const entry of await fs.readdir(current,{withFileTypes:true})) {
      const full=path.join(current,entry.name);
      if (entry.isDirectory()) await walk(full);
      else if (entry.isFile()) out.push(full);
    }
  }
  await walk(dir); return out.sort();
}
async function pinDirectory(dir, pinName) {
  const files=await filesIn(dir);
  if (!files.length) throw new Error(`No files to pin in ${dir}`);
  const form=new FormData();
  for (const file of files) {
    const relative=path.relative(dir,file).split(path.sep).join('/');
    const data=await fs.readFile(file);
    form.append('file',new Blob([data]),relative);
  }
  form.append('pinataOptions',JSON.stringify({cidVersion:1,wrapWithDirectory:true}));
  form.append('pinataMetadata',JSON.stringify({name:pinName,keyvalues:{project:'Morrow',collection:'Moonbound Keepers',fileCount:String(files.length)}}));
  const totalBytes = (await Promise.all(files.map((file) => fs.stat(file)))).reduce((sum, stat) => sum + stat.size, 0);
  console.log(`Uploading ${files.length.toLocaleString()} files (${(totalBytes / (1024 * 1024)).toFixed(1)} MiB) to IPFS: ${pinName}`);
  const response=await fetch('https://api.pinata.cloud/pinning/pinFileToIPFS',{method:'POST',headers:{Authorization:`Bearer ${JWT}`},body:form,signal:AbortSignal.timeout(15*60*1000)});
  const data=await response.json().catch(()=>({}));
  if(!response.ok||!data.IpfsHash)throw new Error(data.error?.details||data.error||`Pinata returned HTTP ${response.status}`);
  return {cid:data.IpfsHash,size:data.PinSize||0,count:files.length};
}

try {
  const expected=1111;
  const imageFiles=await filesIn(path.join(PACK,'images'));
  const metadataFiles=await filesIn(path.join(PACK,'metadata'));
  if(imageFiles.length!==expected||metadataFiles.length!==expected)throw new Error(`Expected 1,111 images and metadata files; found ${imageFiles.length} images / ${metadataFiles.length} metadata.`);
  console.log('Step 1/3 · Pinning image directory. This may take several minutes.');
  const imageDir=await pinDirectory(path.join(PACK,'images'),'moonbound-keepers-images');
  console.log(`Image directory CID: ${imageDir.cid}`);
  console.log('Step 2/3 · Updating metadata image URIs to the real image-directory CID.');
  for(const file of metadataFiles){
    const json=JSON.parse(await fs.readFile(file,'utf8'));
    const leaf=path.basename(file).replace('.json','.webp');
    json.image=`ipfs://${imageDir.cid}/${leaf}`;
    await fs.writeFile(file,JSON.stringify(json,null,2)+'\n');
  }
  console.log('Step 3/3 · Pinning metadata directory.');
  const metadataDir=await pinDirectory(path.join(PACK,'metadata'),'moonbound-keepers-metadata');
  const manifest={
    collection:'Moonbound Keepers',symbol:'MBK',network:'gnoland-1',supply:1111,
    publicMintPriceGnot:575,publicMintPriceUgnot:'575000000',
    imageDirectoryUri:`ipfs://${imageDir.cid}`,metadataDirectoryUri:`ipfs://${metadataDir.cid}`,
    imageDirectoryCid:imageDir.cid,metadataDirectoryCid:metadataDir.cid,
    imageCount:imageDir.count,metadataCount:metadataDir.count,
    note:'CIDs are generated by this run. Set MOONBOUND_IMAGE_BASE_URI and MOONBOUND_METADATA_BASE_URI in .env to the two directory URIs, restart the server, deploy the Morrow registry if needed, and use Creator Studio > Featured Launch > Launch Moonbound Keepers. This step pins files only; it does not deploy a contract or mint NFTs.'
  };
  await fs.writeFile(path.join(PACK,'pinned-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
  await fs.writeFile(path.join(ROOT,'nft-collection','PIN_RESULTS.txt'),`Moonbound Keepers IPFS upload\nImages: ${manifest.imageDirectoryUri}\nMetadata: ${manifest.metadataDirectoryUri}\nSupply: 1,111\nMint price: 575 GNOT (575000000 ugnot)\n\nNext: in Morrow Creator Studio set name=Moonbound Keepers, symbol=MBK, slug=moonbound, supply=1111, mint price=575, and paste these two directory URIs. The cover image must be uploaded separately from the Studio form.\n\nNote: this upload does not deploy the realm or activate minting.\n`);
  console.log('\nPIN COMPLETE');
  console.log(JSON.stringify(manifest,null,2));
} catch(error) {
  console.error(`Collection pin failed: ${error.message}`);
  process.exit(1);
}
